# ram-rescue.sh — AsahiLocker's RAM-only rescue: encrypt the root partition of
# this Mac in place without a USB stick, without a second install, and without
# touching the macOS side.
#
# The rescue is this machine's own kernel with a purpose-built initramfs. It
# carries luks-deploy.sh, every tool that script calls outside its chroot, and
# the cracklib dictionary. GRUB boots it with rd.break=pre-mount: the system
# runs from RAM, nothing on the internal disk is mounted, and luks-deploy.sh can
# encrypt the root partition in place. See docs/RAM-RESCUE.md.
#
#   sudo ./bin/ram-rescue.sh build [--arm] [--console DEV]
#   sudo ./bin/ram-rescue.sh arm       boot the rescue once, at the next reboot
#   sudo ./bin/ram-rescue.sh status
#   sudo ./bin/ram-rescue.sh remove    take the rescue away again
#
# build writes exactly three things, and remove takes all three away:
#   /boot/initramfs-asahilocker-rescue.img
#   /etc/grub.d/42_asahilocker-rescue    its own file: 40_custom is never touched
#   /boot/grub2/grub.cfg                 regenerated by grub2-mkconfig
# arm sets GRUB's one-shot next_entry; nothing else. Logs written by the rescue
# itself go to /boot/asahilocker-rescue-logs/ and never contain key material.
# ═══════════════════════════════════════════════════════════════════════════════
set -euo pipefail

IMG_NAME="initramfs-asahilocker-rescue.img"
IMG="/boot/$IMG_NAME"
GRUB_SNIPPET="/etc/grub.d/42_asahilocker-rescue"
# Exactly this path, never the ESP's grub.cfg: on Fedora that one is a stub
# that chains to this file, and overwriting it breaks the boot.
GRUB_CFG="/boot/grub2/grub.cfg"
ENTRY_TITLE="AsahiLocker RAM rescue (encrypt in place)"
LOG_DIR_NAME="asahilocker-rescue-logs"

SCRIPT_PATH="$(readlink -f "$0")"
REPO_DIR="$(cd "$(dirname "$SCRIPT_PATH")/.." && pwd)"

if [ -t 1 ]; then
    RED=$'\033[0;31m' YEL=$'\033[1;33m' GRN=$'\033[0;32m' BLD=$'\033[1m' NC=$'\033[0m'
else
    RED="" YEL="" GRN="" BLD="" NC=""
fi
log()   { echo "${GRN}[rescue]${NC} $*"; }
warn()  { echo "${YEL}[WARN]${NC}   $*" >&2; }
fatal() { echo "${RED}[ERROR]${NC}  $*" >&2; exit 1; }

usage() {
    sed -n '/^#   sudo \.\/bin\/ram-rescue\.sh build/,/^# itself go to/p' "$SCRIPT_PATH" | sed 's/^# \{0,1\}//'
    exit "${1:-0}"
}

# Every command luks-deploy.sh runs OUTSIDE its chroot, and luks-mount.sh's. dracut prints an error
# for a missing one and still builds the image, so each is checked on the host
# first and found in the finished image afterwards.
REQ_TOOLS="bash cryptsetup btrfs sgdisk partprobe partx blockdev blkid lsblk
  findmnt mount umount mountpoint chroot mktemp awk sed grep tee head tail wc
  sort cut tr stat sync basename dirname readlink date cp mv rm mkdir rmdir
  chmod cat touch env sleep uname df find free seq udevadm lsmod modprobe
  modinfo od install which lsinitrd dmesg id"
# Not called by luks-deploy.sh; there for repairs by hand at the rescue prompt.
EXTRA_TOOLS="dd truncate uniq less vi dmsetup wipefs e2fsck fuser"

# ─── Small helpers ───────────────────────────────────────────────────────────
src_dev() {
    # The block device a mountpoint lives on, with any btrfs [/subvol] removed.
    # Prints nothing, and still returns 0, when nothing is mounted there: the
    # callers test the result, and a non-zero status inside root_dev=$(...)
    # would end the script under set -e before their error message.
    local s
    s=$(findmnt -no SOURCE "$1" 2>/dev/null | sed 's/\[.*//') || true
    [ -n "$s" ] || return 0
    readlink -f "$s"
}

snippet_kver() {
    # The kernel version the installed rescue was built for, from its snippet.
    sed -n 's/^# kernel: //p' "$GRUB_SNIPPET" 2>/dev/null | head -1
}

regen_grub() {
    [ -f "$GRUB_CFG" ] || fatal "$GRUB_CFG not found — refusing to guess where grub.cfg lives."
    grub2-mkconfig -o "$GRUB_CFG" >/dev/null 2>&1 \
        || fatal "grub2-mkconfig -o $GRUB_CFG failed."
}

need_root() {
    [ "$(id -u)" -eq 0 ] || fatal "Run with sudo."
}

# ─── build ───────────────────────────────────────────────────────────────────
cmd_build() {
    local arm=0 console=""
    while [ $# -gt 0 ]; do
        case "$1" in
            --arm) arm=1 ;;
            --console) shift; console="${1:?--console needs a device, e.g. ttyAMA0,115200n8}" ;;
            --console=*) console="${1#--console=}" ;;
            -h|--help) usage 0 ;;
            *) fatal "Unknown option: $1" ;;
        esac
        shift
    done
    need_root

    # ── What this machine is ────────────────────────────────────────────────
    local root_dev boot_dev efi_dev root_fs boot_fs subvol
    root_dev=$(src_dev /)
    root_fs=$(findmnt -no FSTYPE / 2>/dev/null || true)
    [ "$root_fs" = "btrfs" ] || fatal "/ is '$root_fs', not btrfs. The rescue encrypts a Fedora Asahi btrfs root."
    case "$root_dev" in
        /dev/dm-*|/dev/mapper/*)
            fatal "/ is on $root_dev (device-mapper): this system already looks encrypted." ;;
    esac
    [ -b "$root_dev" ] || fatal "Cannot resolve / to a block device (got '$root_dev')."
    subvol=$(findmnt -no OPTIONS / | tr ',' '\n' | sed -n 's/^subvol=\/\{0,1\}//p' | head -1)
    [ -n "$subvol" ] || fatal "Cannot find the btrfs subvolume mounted at /."

    boot_dev=$(src_dev /boot || true)
    [ -n "$boot_dev" ] && [ -b "$boot_dev" ] \
        || fatal "/boot is not a separate partition. The rescue boots from /boot while the root is encrypted."
    [ "$boot_dev" != "$root_dev" ] || fatal "/ and /boot are on the same device."
    boot_fs=$(findmnt -no FSTYPE /boot)
    [ "$boot_fs" = "ext4" ] || fatal "/boot is '$boot_fs', expected ext4 (the Fedora Asahi layout)."
    efi_dev=$(src_dev /boot/efi || true)
    if [ -n "$efi_dev" ] && [ "$(findmnt -no FSTYPE /boot/efi)" != "vfat" ]; then
        efi_dev=""
    fi

    local disk boot_disk
    disk=$(lsblk -dno PKNAME "$root_dev" 2>/dev/null | head -1 || true)
    boot_disk=$(lsblk -dno PKNAME "$boot_dev" 2>/dev/null | head -1 || true)
    [ -n "$disk" ] || fatal "Cannot find the disk under $root_dev."
    [ "$disk" = "$boot_disk" ] \
        || warn "/ ($disk) and /boot ($boot_disk) are on different disks — unusual for Asahi; check the summary below."

    # PARTUUIDs, not filesystem UUIDs: the root's filesystem UUID disappears
    # the moment encryption starts (blkid then sees the LUKS header), but the
    # GPT partition UUID stays the same through every state. A launcher that
    # looked the root up by its btrfs UUID could not find it to resume an
    # interrupted encryption.
    local root_pu boot_pu efi_pu="" boot_uuid
    root_pu=$(blkid -s PARTUUID -o value "$root_dev" 2>/dev/null || true)
    boot_pu=$(blkid -s PARTUUID -o value "$boot_dev" 2>/dev/null || true)
    [ -n "$efi_dev" ] && efi_pu=$(blkid -s PARTUUID -o value "$efi_dev" 2>/dev/null || true)
    boot_uuid=$(blkid -s UUID -o value "$boot_dev" 2>/dev/null || true)
    [ -n "$root_pu" ] && [ -n "$boot_pu" ] && [ -n "$boot_uuid" ] \
        || fatal "Cannot read PARTUUIDs/UUID (root=$root_pu boot=$boot_pu boot-uuid=$boot_uuid)."

    local kver
    kver=$(uname -r)
    [ -f "/boot/vmlinuz-$kver" ] || fatal "/boot/vmlinuz-$kver not found: the running kernel must be in /boot."
    [ -d "/lib/modules/$kver" ] || fatal "/lib/modules/$kver not found."

    # ── Tools on this host ──────────────────────────────────────────────────
    local t missing=()
    for t in dracut lsinitrd grub2-mkconfig grub2-editenv $REQ_TOOLS; do
        command -v "$t" >/dev/null 2>&1 || missing+=("$t")
    done
    if [ ${#missing[@]} -gt 0 ]; then
        fatal "Missing on this system: ${missing[*]}
         (sgdisk is in the gdisk package: sudo dnf install gdisk)"
    fi
    [ -f "$GRUB_CFG" ] || fatal "$GRUB_CFG not found — refusing to guess where grub.cfg lives."
    [ -x "$REPO_DIR/bin/luks-deploy.sh" ] || fatal "$REPO_DIR/bin/luks-deploy.sh not found."
    [ -x "$REPO_DIR/bin/luks-mount.sh" ] || fatal "$REPO_DIR/bin/luks-mount.sh not found."
    bash -n "$REPO_DIR/bin/luks-deploy.sh" || fatal "luks-deploy.sh does not parse."
    bash -n "$REPO_DIR/bin/luks-mount.sh" || fatal "luks-mount.sh does not parse."

    # The cracklib dictionary: with it in the image, cryptsetup's passphrase
    # quality check works in the rescue exactly as on the installed system.
    local dict_files=() f
    for f in /usr/share/cracklib/pw_dict.pwd /usr/share/cracklib/pw_dict.pwd.gz \
             /usr/share/cracklib/pw_dict.pwi /usr/share/cracklib/pw_dict.hwm; do
        [ -f "$f" ] && dict_files+=("$f")
    done
    if [ ${#dict_files[@]} -lt 2 ]; then
        warn "No cracklib dictionary on this system (dnf install cracklib-dicts):"
        warn "  cryptsetup will not be able to check the passphrase in the rescue,"
        warn "  and luks-deploy.sh will turn the check off for that run."
        dict_files=()
    fi

    # Room on /boot: the image is ~60 MB; keep a margin for a kernel update.
    local avail_mb
    avail_mb=$(df --output=avail -BM /boot | tail -1 | tr -dc '0-9')
    [ "${avail_mb:-0}" -ge 200 ] || fatal "Only ${avail_mb} MiB free on /boot; the rescue needs ~60 MiB plus headroom (200)."

    local root_size root_label
    root_size=$(lsblk -dno SIZE "$root_dev" | tr -d ' ')
    root_label=$(blkid -s LABEL -o value "$root_dev" 2>/dev/null || true)

    echo ""
    echo "${BLD}AsahiLocker RAM rescue — build${NC}"
    echo "  model   : $( { tr -d '\0' < /proc/device-tree/model; } 2>/dev/null || echo unknown)"
    echo "  disk    : /dev/$disk"
    echo "  root    : $root_dev  ${root_label:+[$root_label]} $root_size  subvol=$subvol   ← the partition the rescue will encrypt"
    echo "  /boot   : $boot_dev  UUID=$boot_uuid"
    echo "  EFI     : ${efi_dev:-not mounted — luks-deploy.sh will ask}"
    echo "  kernel  : $kver"
    echo "  AsahiLocker: $REPO_DIR"
    echo ""

    # ── Stage the image's extra files ───────────────────────────────────────
    local stage
    stage=$(mktemp -d /tmp/asahilocker-rescue.XXXXXX)
    # shellcheck disable=SC2064  # expand now: $stage is local to this function
    trap "rm -rf '$stage'; rm -f '$IMG.new'" EXIT
    mkdir -p "$stage/AsahiLocker/bin"
    install -m 0755 "$REPO_DIR/bin/luks-deploy.sh" "$REPO_DIR/bin/luks-mount.sh" "$stage/AsahiLocker/bin/"
    install -m 0644 "$REPO_DIR/LICENSE" "$stage/AsahiLocker/"
    [ -f "$REPO_DIR/docs/RAM-RESCUE.md" ] && install -m 0644 "$REPO_DIR/docs/RAM-RESCUE.md" "$stage/AsahiLocker/"

    write_launcher "$stage/asahilocker" "$root_pu" "$boot_pu" "$efi_pu"
    write_banner "$stage/banner.txt" "$stage/banner-hook.sh" "$root_dev" "$root_label" "$root_size"

    # ── Build to a temporary name, verify, then move into place ────────────
    log "Building the rescue initramfs (about a minute)..."
    local dracut_log="$stage/dracut.log"
    local -a inst_args=()
    for t in $REQ_TOOLS; do inst_args+=("$(command -v "$t")"); done
    if ! dracut --force --quiet --no-hostonly-cmdline \
            --add "crypt dm btrfs" \
            --omit "plymouth" \
            --install "${inst_args[*]} ${dict_files[*]}" \
            --install-optional "$EXTRA_TOOLS" \
            --include "$stage/AsahiLocker" /root/AsahiLocker \
            --include "$stage/asahilocker" /usr/bin/asahilocker \
            --include "$stage/AsahiLocker/bin/luks-mount.sh" /usr/bin/luks-mount \
            --include "$stage/banner.txt" /etc/asahilocker-banner.txt \
            --include "$stage/banner-hook.sh" /var/lib/dracut/hooks/emergency/99-asahilocker-banner.sh \
            "$IMG.new" "$kver" > "$dracut_log" 2>&1; then
        tail -20 "$dracut_log" >&2
        fatal "dracut failed; nothing was installed."
    fi

    log "Verifying the image..."
    local list
    list=$(lsinitrd "$IMG.new" 2>/dev/null) || fatal "lsinitrd cannot read the new image."
    local fail=0
    in_image() { grep -qE "(^| )$1( |$)" <<< "$list"; }
    for f in root/AsahiLocker/bin/luks-deploy.sh root/AsahiLocker/bin/luks-mount.sh usr/bin/luks-mount \
             usr/bin/asahilocker etc/asahilocker-banner.txt \
             var/lib/dracut/hooks/emergency/99-asahilocker-banner.sh; do
        in_image "$f" || { warn "  missing from image: /$f"; fail=1; }
    done
    for t in $REQ_TOOLS; do
        in_image "(usr/)?s?bin/$t" || { warn "  missing from image: $t"; fail=1; }
    done
    for f in ${dict_files[@]+"${dict_files[@]}"}; do
        in_image "${f#/}" || { warn "  missing from image: $f"; fail=1; }
    done
    # Kernel modules: dm-crypt and btrfs, plus every driver between the root
    # partition and the bus (nvme-apple on a Mac). Built-ins need no file.
    local m mods=(dm_crypt btrfs) p
    p=$(readlink -f "/sys/class/block/$disk/device" 2>/dev/null || true)
    while [ -n "$p" ] && [ "$p" != "/sys" ] && [ "$p" != "/sys/devices" ] && [ "$p" != "/" ]; do
        if [ -e "$p/driver/module" ]; then
            mods+=("$(basename "$(readlink -f "$p/driver/module")")")
        fi
        p=$(dirname "$p")
    done
    for m in "${mods[@]}"; do
        if grep -qE "/${m//_/[-_]}\.ko" "/lib/modules/$kver/modules.builtin" 2>/dev/null; then
            continue
        fi
        in_image ".*/${m//_/[-_]}\.ko(\.[a-z]+)?" || { warn "  missing from image: kernel module $m"; fail=1; }
    done
    [ "$fail" -eq 0 ] || fatal "The image is incomplete (above). Nothing was installed; GRUB is untouched."
    log "  OK: luks-deploy.sh, launcher, ${#mods[@]} kernel modules ($(echo "${mods[@]}" | tr ' ' ',')), $(wc -w <<< "$REQ_TOOLS") tools${dict_files[0]:+, cracklib dictionary}."

    # ── Install: image first, then the GRUB entry that points at it ────────
    mv -f "$IMG.new" "$IMG"
    sync
    write_snippet "$GRUB_SNIPPET.new" "$kver" "$boot_uuid" "$console"
    mv -f "$GRUB_SNIPPET.new" "$GRUB_SNIPPET"
    log "Regenerating $GRUB_CFG..."
    if ! regen_grub || ! grep -qF "menuentry '$ENTRY_TITLE'" "$GRUB_CFG"; then
        rm -f "$GRUB_SNIPPET"
        regen_grub || true
        fatal "The rescue entry did not appear in $GRUB_CFG; it has been taken out again."
    fi
    command -v restorecon >/dev/null 2>&1 && restorecon -F "$IMG" "$GRUB_SNIPPET" "$GRUB_CFG" 2>/dev/null || true
    trap - EXIT
    rm -rf "$stage"

    echo ""
    log "${BLD}Rescue ready${NC}: $IMG ($(du -h "$IMG" | cut -f1)), GRUB entry \"$ENTRY_TITLE\"."
    if [ "$arm" -eq 1 ]; then
        cmd_arm
    else
        echo "  Next: sudo $0 arm && sudo reboot"
    fi
}

# The launcher inside the image. PARTUUIDs are baked in, so the rescue only
# ever acts on the partitions of the install it was built on.
write_launcher() {
    local out="$1" root_pu="$2" boot_pu="$3" efi_pu="$4"
    {
        echo '#!/bin/bash'
        echo "# AsahiLocker RAM rescue launcher. Generated by bin/ram-rescue.sh on $(hostname) $(date '+%Y-%m-%d %H:%M')."
        echo "ROOT_PARTUUID='$root_pu'"
        echo "BOOT_PARTUUID='$boot_pu'"
        echo "EFI_PARTUUID='$efi_pu'"
        echo "LOG_DIR_NAME='$LOG_DIR_NAME'"
        cat <<'LAUNCHER'
set -u

by_partuuid() {
    local d
    [ -n "$1" ] || return 1
    d=$(readlink -f "/dev/disk/by-partuuid/$1" 2>/dev/null) || return 1
    [ -b "$d" ] && echo "$d"
}

udevadm settle --timeout=10 2>/dev/null || true
ROOT_DEV=$(by_partuuid "$ROOT_PARTUUID") || ROOT_DEV=""
BOOT_DEV=$(by_partuuid "$BOOT_PARTUUID") || BOOT_DEV=""
EFI_DEV=$(by_partuuid "$EFI_PARTUUID") || EFI_DEV=""
if [ -z "$ROOT_DEV" ] || [ -z "$BOOT_DEV" ]; then
    echo "ERROR: the partitions this rescue was built for are not here" >&2
    echo "  (root PARTUUID $ROOT_PARTUUID, /boot PARTUUID $BOOT_PARTUUID)." >&2
    echo "  The rescue only works on the Mac, and the disk, it was built on." >&2
    lsblk -o NAME,SIZE,FSTYPE,LABEL,PARTUUID >&2
    exit 1
fi
for _d in "$ROOT_DEV" "$BOOT_DEV" ${EFI_DEV:+"$EFI_DEV"}; do
    if findmnt -rn -S "$_d" >/dev/null 2>&1; then
        echo "ERROR: $_d is mounted. Nothing on the target may be mounted here." >&2
        exit 1
    fi
done
mountpoint -q /dev/pts 2>/dev/null || { mkdir -p /dev/pts; mount -t devpts devpts /dev/pts; } 2>/dev/null || true

# Keep the logs at /boot whatever happens — but never key material. The state
# directory holds the recovery key and a LUKS header backup; /boot is not
# encrypted, so only the named, key-free files below are copied.
save_logs() {
    local rc=$? mp=/run/asahilocker-bootlogs dest s f
    trap - EXIT
    mkdir -p "$mp"
    if mount "$BOOT_DEV" "$mp" 2>/dev/null; then
        dest="$mp/$LOG_DIR_NAME/$(date +%Y%m%d_%H%M%S)"
        mkdir -p "$dest" && chmod 0700 "$mp/$LOG_DIR_NAME" "$dest"
        cp /root/AsahiLocker/bin/luks-deploy-*.log "$dest/" 2>/dev/null
        dmesg > "$dest/dmesg.txt" 2>/dev/null
        lsblk -o NAME,SIZE,FSTYPE,LABEL,UUID,PARTUUID > "$dest/lsblk.txt" 2>/dev/null
        cp /run/initramfs/rdsosreport.txt "$dest/" 2>/dev/null
        for s in /root/AsahiLocker/bin/pre-luks-state-*/; do
            [ -d "$s" ] || continue
            mkdir -p "$dest/$(basename "$s")"
            for f in fstab grub-defaults kernel-cmdline crypttab lsblk.txt blkid.txt btrfs-subvols.txt; do
                [ -f "$s$f" ] && cp "$s$f" "$dest/$(basename "$s")/"
            done
            cp "$s"*.conf "$dest/$(basename "$s")/" 2>/dev/null
        done
        echo "$rc" > "$dest/exit-code"
        sync
        umount "$mp" 2>/dev/null
        echo ""
        echo "Logs (no keys) saved to /boot/$LOG_DIR_NAME/$(basename "$dest")/"
    else
        echo "" >&2
        echo "WARNING: could not mount $BOOT_DEV to save the logs." >&2
    fi
    rmdir "$mp" 2>/dev/null
    if [ "$rc" -ne 0 ]; then
        for s in /root/AsahiLocker/bin/pre-luks-state-*/recovery-key.txt; do
            [ -f "$s" ] || continue
            echo "" >&2
            echo "  A recovery key was enrolled in this run, and this RAM holds" >&2
            echo "  its only copy: $s" >&2
            echo "  Write it down before you reboot (cat that file), or re-run" >&2
            echo "  'asahilocker' now: a completed run copies it onto the" >&2
            echo "  encrypted system." >&2
        done
    fi
    exit "$rc"
}
trap save_logs EXIT
trap 'exit 130' INT TERM

export LUKS_TARGET_ROOT="$ROOT_DEV" LUKS_TARGET_BOOT="$BOOT_DEV"
[ -n "$EFI_DEV" ] && export LUKS_TARGET_EFI="$EFI_DEV"
cd /root/AsahiLocker/bin || exit 1
# On the console directly, not through a pipe: the passphrase prompts need it.
./luks-deploy.sh "$@"
LAUNCHER
    } > "$out"
    chmod 0755 "$out"
}

# The banner, and the dracut hook that shows it. dracut's emergency shell is a
# plain non-login sh, which reads no profile of its own, but dracut-emergency
# runs the "emergency" hooks and then sources /etc/profile, after its own
# messages and right before the prompt. The hook makes /etc/profile print the
# banner there. (dracut writes a fresh /etc/profile for every shell.)
write_banner() {
    local out="$1" hook="$2" dev="$3" label="$4" size="$5"
    cat > "$out" <<BANNER

  ════════════════════════════════════════════════════════════════
   AsahiLocker RAM rescue. The system is running from RAM, and
   nothing on the internal disk is mounted.

   To encrypt $dev ${label:+[$label] }($size) in place, type:

       asahilocker

   It resumes an interrupted encryption the same way.
   To look inside an install instead:    luks-mount list
                                         luks-mount chroot /dev/...
   To leave without changing anything:   reboot -f
  ════════════════════════════════════════════════════════════════

BANNER
    cat > "$hook" <<'HOOK'
# AsahiLocker RAM rescue (bin/ram-rescue.sh): show what to type at the prompt.
grep -q asahilocker-banner /etc/profile 2>/dev/null \
    || echo '[ -r /etc/asahilocker-banner.txt ] && cat /etc/asahilocker-banner.txt' >> /etc/profile
HOOK
}

# The GRUB entry. root= names the /boot filesystem on purpose: it is a device
# the initrd finds at once in every state of the root partition (plain btrfs,
# half-encrypted, encrypted), so the rescue reaches its prompt immediately on
# a resume too, instead of waiting out a timeout for a btrfs UUID that the
# LUKS header has hidden. rd.break=pre-mount stops before anything is mounted,
# rd.luks=0 keeps the initrd from unlocking anything itself, and the rescue
# runs without plymouth so the console is a plain terminal.
write_snippet() {
    local out="$1" kver="$2" boot_uuid="$3" console="$4"
    local cmdline="root=UUID=$boot_uuid rootfstype=ext4 ro rd.break=pre-mount rd.luks=0 rd.lvm=0 rd.md=0 rd.plymouth=0 plymouth.enable=0 fsck.mode=skip rd.shell SYSTEMD_SULOGIN_FORCE=1 systemd.show_status=1 console=tty0"
    [ -n "$console" ] && cmdline="$cmdline console=$console"
    cat > "$out" <<SNIPPET
#!/bin/sh
exec tail -n +3 "\$0"
# AsahiLocker RAM rescue (bin/ram-rescue.sh). Remove with: ram-rescue.sh remove
# kernel: $kver
menuentry '$ENTRY_TITLE' --class fedora --class gnu-linux --class os --id asahilocker-rescue {
    insmod part_gpt
    insmod ext2
    search --no-floppy --fs-uuid --set=root $boot_uuid
    linux /vmlinuz-$kver $cmdline
    initrd /$IMG_NAME
}
SNIPPET
    chmod 0755 "$out"
}

# ─── arm ─────────────────────────────────────────────────────────────────────
cmd_arm() {
    need_root
    [ -f "$IMG" ] && [ -f "$GRUB_SNIPPET" ] || fatal "No rescue installed. Run: sudo $0 build"
    grep -qF "menuentry '$ENTRY_TITLE'" "$GRUB_CFG" \
        || fatal "The rescue entry is not in $GRUB_CFG. Run: sudo $0 build"
    local kv
    kv=$(snippet_kver)
    [ -f "/boot/vmlinuz-$kv" ] || fatal "The rescue was built for kernel $kv, which is no longer in /boot. Run: sudo $0 build"
    grub2-reboot "$ENTRY_TITLE" || fatal "grub2-reboot failed."
    log "Armed: the NEXT boot, and only that one, starts the rescue. Then: sudo reboot"
    log "  (Changed your mind? sudo grub2-editenv - unset next_entry)"
}

# ─── status ──────────────────────────────────────────────────────────────────
cmd_status() {
    need_root      # grubenv and the image are root-only
    local kv next
    if [ -f "$IMG" ]; then
        echo "image   : $IMG ($(du -h "$IMG" | cut -f1))"
    else
        echo "image   : not installed"
    fi
    if [ -f "$GRUB_SNIPPET" ]; then
        kv=$(snippet_kver)
        echo "entry   : $GRUB_SNIPPET (kernel $kv$([ -f "/boot/vmlinuz-$kv" ] || echo ' — MISSING from /boot, rebuild'))"
        grep -qF "menuentry '$ENTRY_TITLE'" "$GRUB_CFG" 2>/dev/null \
            && echo "grub.cfg: entry present" || echo "grub.cfg: entry NOT present — run build again"
    else
        echo "entry   : not installed"
    fi
    next=$(grub2-editenv list 2>/dev/null | sed -n 's/^next_entry=//p' || true)
    if [ "$next" = "$ENTRY_TITLE" ]; then echo "armed   : yes — the next boot starts the rescue"
    else echo "armed   : no"; fi
    case "$(src_dev /)" in
        /dev/dm-*|/dev/mapper/*) echo "root    : encrypted (on $(src_dev /)) — the rescue can be removed" ;;
        *) echo "root    : not encrypted ($(src_dev /))" ;;
    esac
    if [ -d "/boot/$LOG_DIR_NAME" ]; then
        echo "logs    : /boot/$LOG_DIR_NAME/ ($(find "/boot/$LOG_DIR_NAME" -mindepth 1 -maxdepth 1 -type d 2>/dev/null | wc -l) runs)"
    fi
}

# ─── remove ──────────────────────────────────────────────────────────────────
cmd_remove() {
    need_root
    local next changed=0
    next=$(grub2-editenv list 2>/dev/null | sed -n 's/^next_entry=//p' || true)
    if [ "$next" = "$ENTRY_TITLE" ]; then
        grub2-editenv - unset next_entry && log "Disarmed the one-shot boot."
    fi
    if [ -f "$GRUB_SNIPPET" ]; then
        rm -f "$GRUB_SNIPPET"; changed=1; log "Removed $GRUB_SNIPPET."
    fi
    if [ -f "$IMG" ] || [ -f "$IMG.new" ]; then
        rm -f "$IMG" "$IMG.new"; log "Removed $IMG."
    fi
    if [ "$changed" -eq 1 ] || grep -qF "menuentry '$ENTRY_TITLE'" "$GRUB_CFG" 2>/dev/null; then
        regen_grub
        grep -qF "menuentry '$ENTRY_TITLE'" "$GRUB_CFG" && fatal "The entry is still in $GRUB_CFG."
        log "Regenerated $GRUB_CFG; the rescue entry is gone."
    fi
    [ -d "/boot/$LOG_DIR_NAME" ] && log "Kept /boot/$LOG_DIR_NAME/ (logs only, no keys); delete it when you like."
    log "Done."
}

case "${1:-}" in
    build)  shift; cmd_build "$@" ;;
    arm)    cmd_arm ;;
    status) cmd_status ;;
    remove) cmd_remove ;;
    -h|--help|help) usage 0 ;;
    *) usage 1 ;;
esac
